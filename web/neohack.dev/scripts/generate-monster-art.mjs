import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { monsterRoster } from "./monster-roster.mjs";
const root = resolve(import.meta.dirname, ".."),
  roster = monsterRoster();
const recipe = JSON.parse(
  readFileSync(resolve(root, "art/monster-families.json"), "utf8"),
);
const entries = {},
  ambiguous = new Set();
for (const row of roster.rows) {
  const defaults = recipe.groups[row.group];
  if (!defaults) throw Error("Unmapped authoring group " + row.group);
  const [family, defaultSize, defaultPalette] = defaults;
  for (const name of row.aliases) {
    const size = /\b(baby|cub|pup|hatchling|small|little|kitten)\b/i.test(name)
      ? "small"
      : /\b(giant|large)\b/i.test(name)
        ? "large"
        : defaultSize;
    // Color adjectives already in the disclosed name, not engine color/resistance
    // tables. Unnamed colors use the family's neutral authored palette.
    const color =
      /\b(red|orange|gold|golden|yellow|white|silver|gray|grey|black|blue|green|brown|purple|violet)\b/i
        .exec(name)?.[1]
        .toLowerCase();
    const palette = color
      ? {
          red: "clay",
          orange: "clay",
          gold: "amber",
          golden: "amber",
          yellow: "amber",
          white: "ivory",
          silver: "ivory",
          gray: "slate",
          grey: "slate",
          black: "ink",
          blue: "mist",
          green: "sage",
          brown: "earth",
          purple: "plum",
          violet: "plum",
        }[color]
      : defaultPalette;
    const value = {
      family,
      size,
      palette,
      ...recipe.overrides[row.appearance],
      ...recipe.overrides[name],
    };
    if (
      entries[name] &&
      JSON.stringify(entries[name]) !== JSON.stringify(value)
    ) {
      ambiguous.add(name);
      delete entries[name];
    } else if (!ambiguous.has(name)) entries[name] = value;
  }
}
const output =
  '/** Generated by scripts/generate-monster-art.mjs from the pinned source.\n * Appearance lookup only: no hidden IDs, combat data, ranks or spawn tables.\n * Ambiguous names deliberately have no recipe; never resolve them from glyphs. */\nimport type {CreatureRecipe} from "./creature-families";\nexport const monsterAppearances: Readonly<Record<string, CreatureRecipe>> = ' +
  JSON.stringify(entries, null, 2) +
  ";\n";
const path = resolve(root, "src/monster-appearances.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output)
    throw Error("Monster artwork mapping drift");
} else writeFileSync(path, output);
console.log(
  JSON.stringify({
    definitions: roster.rows.length,
    appearanceRecipes: Object.keys(entries).length,
    ambiguousAppearances: ambiguous.size,
    families: new Set(Object.values(entries).map((e) => e.family)).size,
    sourceSha256: roster.sha256,
  }),
);
