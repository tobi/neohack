export function drawEquipment(c: CanvasRenderingContext2D, name: string, x = 0, y = 0) {
  for (const [row, pixels] of equipmentPixels[name]!.entries())
    for (const [col, pixel] of [...pixels].entries()) if (pixel !== '.') {
      c.fillStyle = equipmentPalette[pixel]!;
      c.fillRect(x + col, y + row, 1, 1);
    }
}
