import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,rename} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {execFileSync} from 'node:child_process';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
import {root,identity} from './native-fixture.mjs';
test('installed Bun MCP relocates with WASM and needs no native engine or data arguments',async t=>{
  const dir=await mkdtemp(tmpdir()+'/mcp-install-');t.after(()=>rm(dir,{recursive:true,force:true}));
  execFileSync(process.execPath,[root+'/scripts/install-mcp.mjs',dir+'/original']);await rename(dir+'/original',dir+'/moved');
  const client=new Client({name:'install',version:'1'});t.after(()=>client.close());
  await client.connect(new StdioClientTransport({command:dir+'/moved/bin/neohack-mcp',args:['--sessions',dir+'/sessions'],stderr:'pipe'}));
  const r=await client.callTool({name:"session",arguments:{action: "create", ...(identity)}});assert.equal(r.isError,false,JSON.stringify(r));
  const frame=r.structuredContent;
  assert.equal(frame.version,2);assert.match(frame.basis.sessionId,/^[\w-]{16}$/);
  assert.equal(frame.scene.kind,'snapshot');assert.equal(frame.control.gate,'ready');
  const waited=await client.callTool({name:"interact",arguments:{action: "rest", sessionId:frame.basis.sessionId,viewId:frame.basis.viewId,includeWorld:true}});
  assert.equal(waited.isError,false,JSON.stringify(waited));
  assert.equal(waited.structuredContent.basis.turn,frame.basis.turn+1);
  assert.ok(waited.structuredContent.scene.world.length,'relocated WASM returns actual perceived cells');
  assert.ok((await client.listTools()).tools.some(t=>t.name==='travel'));
});
