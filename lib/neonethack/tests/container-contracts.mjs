// Real seeded containers through the public API, shared by native and WASM.
import {test} from 'node:test';
import assert from 'node:assert/strict';
const hero = {name:'Chest', seed:4, role:'valkyrie', race:'human', gender:'female', align:'lawful'};
const path = ['north','north','east','east','east'];
const offer = game => game.observation.neighborhood.cells.find(c => !c.dx && !c.dy).actions.find(a => a.key === 'loot');
const choose = async (game, label) => {
  const d = game.decision;
  assert.equal(d?.kind, 'choice');
  const option = d.options.find(o => o.label === label);
  assert.ok(option, 'Missing engine choice: ' + label);
  return game.answer(d.id, {kind:'choice', choose:[option.id]});
};
export function containerContracts(name, fixture) {
  test(`${name}: using a carried sack suspends at its own container decision`, async t => {
    const b = await fixture(t);
    let game = await b.api.create({...hero,role:'archeologist',seed:14});
    const sack = game.observation.inventory.find(i=>/sack/.test(i.label));
    await game.apply({id:sack.id});
    if (game.decision.containerPhase === 'inspect') await choose(game,'Look inside');
    assert.equal(game.decision.kind,'choice');
    assert.equal(game.decision.containerPhase,'transfer');
    assert.ok(game.decision.options.some(o=>o.transfer === 'put'));
    const d = game.decision;
    game = await b.restart(game);
    assert.deepEqual(game.decision,d);
    await game.cancel(game.decision.id);
    assert.ok(game.observation.inventory.some(i=>i.id === sack.id));
  });
  test(`${name}: cancelling a container draft moves nothing; only new inspection costs a turn`, async t => {
    const b = await fixture(t), game = await b.api.create(hero);
    for (const direction of path) await game.move(direction);
    const before = game.observation;
    await game.loot();
    await game.cancel(game.decision.id);
    assert.equal(game.observation.turn, before.turn, 'declining inspection is free');
    await game.loot();
    await choose(game, 'Look inside');
    await game.cancel(game.decision.id);
    assert.equal(game.observation.turn, before.turn + 1, 'discovering contents costs one turn');
    assert.deepEqual(game.observation.inventory, before.inventory);
    const turn = game.observation.turn;
    await game.loot();
    assert.equal(game.decision.containerPhase, 'transfer');
    await game.cancel(game.decision.id);
    assert.equal(game.observation.turn, turn, 'reviewing known contents is free');
    assert.deepEqual(game.observation.inventory, before.inventory);
  });
  test(`${name}: containers require standing underfoot; contents and transfers retain exact decisions and receipts`, async t => {
    const b = await fixture(t);
    let game = await b.api.create(hero);
    const before = game.state;
    assert.equal(offer(game).availability, 'knownBlocked');
    await assert.rejects(game.loot(), e => e.response.error.code === 'noPerceivedContainers');
    assert.equal(game.observation.turn, before.observation.turn);
    for (const direction of path.slice(0,-1)) await game.move(direction);
    assert.equal(offer(game).availability, 'knownBlocked', 'an adjacent chest is not underfoot');
    await game.move(path.at(-1));
    assert.equal(offer(game).availability, 'attemptable');
    const chest = game.observation.here.items[0];
    assert.match(chest.label, /chest/);
    assert.equal(game.observation.here.items.length, 1, 'contents are not ground items');
    const revision = game.state.revision;
    const opened = await game.loot({expectedRevision:revision});
    assert.equal(opened.decision.kind, 'choice');
    assert.equal(opened.decision.containerPhase, 'inspect');
    assert.deepEqual(opened.decision.options.map(o=>o.label), ['Look inside']);
    assert.deepEqual(await b.api.request('game.loot', {sessionId:game.id, expectedRevision:revision, requestId:opened.requestId}), opened);
    game = await b.restart(game);
    assert.deepEqual(game.decision, opened.decision, 'opening decision survives restart without answering');
    const looked = await choose(game, 'Look inside');
    assert.ok(looked.events.some(e => e.type === 'heard' && e.text.includes('purple-red potion')));
    assert.equal(game.observation.here.items.length, 1);
    const taking = looked;
    assert.equal(taking.decision.containerPhase, 'transfer');
    assert.deepEqual(taking.decision.options.filter(o=>o.transfer === 'take').map(o=>o.label), ['a purple-red potion']);
    const food = taking.decision.options.find(o=>o.transfer === 'put' && /food ration/.test(o.label));
    assert.ok(food, 'backpack and container are offered together');
    game = await b.restart(game);
    assert.deepEqual(game.decision, taking.decision, 'content selection survives restart');
    await assert.rejects(game.answer(game.decision.id, {kind:'choice', choose:[999999]}));
    assert.deepEqual(game.decision, taking.decision, 'bad IDs do not select another item');
    const d = game.decision, takeRevision = game.state.revision;
    const answer = {kind:'choice', choose:[d.options.find(o=>o.transfer === 'take').id, food.id]};
    const taken = await game.answer(d.id, answer);
    assert.equal(taken.decision, null);
    assert.equal(taken.observation.here.items[0].id, chest.id);
    const potion = game.observation.inventory.find(i=>i.label === 'a purple-red potion');
    assert.ok(potion);
    assert.equal(game.observation.inventory.some(i=>/food ration/.test(i.label)), false, 'one answer takes and puts');
    assert.deepEqual(await b.api.request('decision.answer', {sessionId:game.id, expectedRevision:takeRevision, requestId:taken.requestId, decisionId:d.id, answer}), taken);
    await game.loot();
    assert.equal(game.decision.containerPhase, 'transfer', 'known contents bypass inspection and category menus');
    assert.ok(game.decision.options.some(o=>o.transfer === 'take' && /food ration/.test(o.label)));
    const putting = game.state;
    const option = putting.decision.options.find(o=>o.transfer === 'put' && o.label === potion.label);
    assert.ok(option);
    await game.answer(putting.decision.id, {kind:'choice',choose:[option.id]});
    assert.equal(game.observation.inventory.some(i=>i.id === potion.id), false);
    assert.equal(game.observation.here.items.length, 1);
    const final = game.observation;
    game = await b.restart(game);
    assert.deepEqual(game.observation, final);
  });
  test(`${name}: locked containers reveal their lock only after an attempt, and never auto-unlock`, async t => {
    const b = await fixture(t), game = await b.api.create({...hero, seed:24});
    for (const direction of ['north','north','north','east','east','east','east','east','east']) await game.move(direction);
    const original = game.observation.here.items[0];
    assert.equal(/locked/.test(original.label), false);
    assert.equal(offer(game).availability, 'attemptable');
    const r = await game.loot();
    assert.equal(r.decision, null);
    assert.equal(r.outcome.status, 'blocked');
    assert.ok(r.events.some(e=>e.type === 'heard' && /locked/.test(e.text)));
    assert.match(game.observation.here.items[0].label, /locked chest/);
    assert.equal(game.observation.here.items[0].id, original.id);
  });
  test(`${name}: multiple containers are selected by engine choice ID; cancel leaves both in place`, async t => {
    const b = await fixture(t), game = await b.api.create({...hero, role:'archeologist', seed:14});
    for (const direction of ['north','north','north','north','north','east','east']) await game.move(direction);
    const sack = game.observation.inventory.find(i=>/sack/.test(i.label));
    assert.ok(sack);
    await game.drop({id:sack.id});
    const items = game.observation.here.items;
    assert.equal(items.length, 2);
    await game.loot();
    assert.equal(game.decision.about, 'Loot which containers?');
    assert.equal(game.decision.options.length, 2);
    const option = game.decision.options.find(o=>/sack/.test(o.label));
    await game.answer(game.decision.id, {kind:'choice',choose:[option.id]});
    assert.match(game.decision.about, /sack/);
    await game.cancel(game.decision.id);
    assert.equal(game.decision, null);
    assert.deepEqual(game.observation.here.items.map(i=>i.id).sort(), items.map(i=>i.id).sort());
  });
}
